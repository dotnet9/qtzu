// ---------- 组装输出 ----------
const fmtUni = (a) => ({
  zh: a[0], en: a[1], tag: a[2] || null, founded: a[3], site: `https://www.${a[4]}`,
  globalRank: a[5], nationalRank: a[6], bearing: a[7], history: a[8] || '', campusNote: a[9] || null,
});
const fmtItem = (a) => ({ name: a[0], en: a[1], desc: a[2], img: a[3] ? IMG(a[3]) : null, bearing: a[4] || null });

function emit(cityId) {
  const m = META[cityId];
  const dir = join(ROOT, cityId);
  mkdirSync(dir, { recursive: true });
  mkdirSync(join(dir, 'img'), { recursive: true });
  const unis = (UNIS[cityId] || []).map(fmtUni);
  const foods = (FOODS[cityId] || []).map(fmtItem);
  const scenes = (SCENES[cityId] || []).map(fmtItem);
  const city = {
    id: cityId, name: m.name, en: m.en, color: m.color, landmark: m.landmark, region: m.region,
    importance: m.importance, isCoastal: !!m.isCoastal,
    history: m.history,
    gallery: (m.gallery || []).map(([f, cap]) => ({ img: IMG(f, 960), caption: cap })),
    variants: VARIANTS[cityId]
      ? VARIANTS[cityId].map(v => ({ emoji: v[0], intro: v[1], introEn: v[2], words: v[3], deco: v[4] }))
      : [{ emoji: '🏙️', intro: `${m.name}欢迎你！`, introEn: `Welcome to ${m.en}.`, words: [], deco: 'lantern' }],
    level: {
      radius: cityId === 'beijing' ? 34 : 28,
      eggCount: cityId === 'beijing' ? 15 : 12,
      landmarks: [m.landmark, 'pavilion', 'tower'],
      paths: true,
      districts: m.isCoastal ? ['port', 'food-street', 'park', 'old-street']
        : ['food-street', 'park', 'old-street', 'plaza'],
      highlands: [{ x: 0.55, z: -0.55, h: 1.6 }],
      eggsOnSigns: 5,
      // shape: 城市真实轮廓多边形（归一化 0~1 坐标），缺省用有机不规则形状
      shape: m.shape || null,
    },
  };
  const put = (n, o) => writeFileSync(join(dir, n), JSON.stringify(o, null, 2) + '\n');
  put('city.json', city);
  put('universities.json', { city: cityId, source: '各高校官网与教育部全国高等学校名单', unis });
  put('foods.json', { city: cityId, source: '地方政府门户与权威美食名录', items: foods });
  put('scenes.json', { city: cityId, source: '地方政府门户与世界遗产名录等官方资料', items: scenes });
  console.log(`${cityId}: unis=${unis.length} foods=${foods.length} scenes=${scenes.length}`);
}

const only = process.argv.slice(2);
const ids = only.length ? only : Object.keys(META);
for (const id of ids) emit(id);
